#include "libft.h"

void	*ft_memset(void *b, int c, size_t len)
{
	unsigned char	*p;
	unsigned char	ch;

	p = (unsigned char *)b;
	ch = c;
	while (len > 0)
	{
		*p = ch;
		p++;
		len--;
	}
	return (b);
}
